import { flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import PayoutsView from '../PayoutsView.vue'
const stepRun = vi.hoisted(() => vi.fn())
const api = vi.hoisted(() => ({ listPayouts: vi.fn(), listDestinations: vi.fn(), getSupplierOptions: vi.fn(), getEarnings: vi.fn(), requestPayout: vi.fn(), cancelPayout: vi.fn(), getPayoutOperation: vi.fn(), getPayout: vi.fn() }))
vi.mock('@/api/supplier', () => api)
vi.mock('@/stores/workMode', () => ({ useWorkModeStore: () => ({ dirty: false }) }))
vi.mock('@/stores/auth', () => ({ useAuthStore: () => ({ user: { id: 42 } }) }))
vi.mock('vue-i18n', async () => ({ ...(await vi.importActual<typeof import('vue-i18n')>('vue-i18n')), useI18n: () => ({ t: (key: string) => key }) }))
vi.mock('@/composables/useStepUp', () => ({ useStepUp: () => ({ run: stepRun }), isStepUpCancelled: () => false }))
const mountView = () => mount(PayoutsView, { global: { stubs: { AppLayout: { template: '<div><slot /></div>' }, TotpStepUpDialog: true, RouterLink: { template: '<a><slot /></a>' } } } })
beforeEach(() => {
  vi.clearAllMocks(); sessionStorage.clear(); stepRun.mockImplementation((action: () => Promise<unknown>) => action())
  api.listPayouts.mockResolvedValue([])
  api.listDestinations.mockResolvedValue([{ id: 1, masked_label: 'Bank ****1234', verified: true, version: 1 }])
  api.getSupplierOptions.mockResolvedValue({ minimum_payout_usd: '10.00' })
  api.getEarnings.mockResolvedValue({ items: [], wallet: { pending: '2.00', available: '30.00', payout_reserved: '4.00', debt: '0', currency: 'USD' } })
})
describe('supplier payouts', () => {
  it('shows wallet balances separately and rejects invalid or below-minimum amounts', async () => {
    const w = mountView(); await flushPromises()
    for (const s of ['2.00', '30.00', '4.00']) expect(w.text()).toContain(s)
    await w.get('[data-test=destination]').setValue('1')
    await w.get('[data-test=amount]').setValue('9.99')
    expect(w.get('[data-test=request]').attributes('disabled')).toBeDefined()
    await w.get('[data-test=amount]').setValue('10.001')
    expect(w.get('[data-test=request]').attributes('disabled')).toBeDefined()
    await w.get('[data-test=amount]').setValue('10.00')
    expect(w.get('[data-test=request]').attributes('disabled')).toBeUndefined()
  })
  it('loads payout details from the server', async () => {
    const payout = { id: 7, masked_label: '****1234', amount: '10.00', currency: 'USD', status: 'paid', created_at: '2026-01-01', external_reference: 'bank-ref' }
    api.listPayouts.mockResolvedValue([payout]); api.getPayout.mockResolvedValue(payout)
    const w = mountView(); await flushPromises()
    await w.get('[data-test=payout-detail]').trigger('click'); await flushPromises()
    expect(api.getPayout).toHaveBeenCalledWith(7)
    expect(document.body.textContent).toContain('bank-ref')
    w.unmount()
  })
  it('keeps the operation key when step-up retries the request', async () => {
    api.requestPayout.mockRejectedValueOnce({ code: 'STEP_UP_REQUIRED' }).mockResolvedValueOnce({ id: 5 })
    stepRun.mockImplementation(async (action: () => Promise<unknown>) => { try { return await action() } catch { return action() } })
    const w = mountView(); await flushPromises()
    await w.get('[data-test=destination]').setValue('1'); await w.get('[data-test=amount]').setValue('10.00')
    await w.get('[data-test=request]').trigger('click'); await flushPromises()
    expect(api.requestPayout).toHaveBeenCalledTimes(2)
    expect(api.requestPayout.mock.calls[1]).toEqual(api.requestPayout.mock.calls[0])
  })
  it('locks an uncertain submission and checks its operation before allowing another', async () => {
    api.requestPayout.mockRejectedValue({ status: 0 })
    api.getPayoutOperation.mockResolvedValue({ operation_status: 'not_found' })
    const w = mountView(); await flushPromises()
    await w.get('[data-test=destination]').setValue('1'); await w.get('[data-test=amount]').setValue('10.00')
    await w.get('[data-test=request]').trigger('click'); await flushPromises()
    expect(api.requestPayout).toHaveBeenCalledTimes(1)
    expect(w.text()).toContain('marketplace.operationUnknown')
    expect(w.get('[data-test=request]').attributes('disabled')).toBeDefined()
    await w.get('[data-test=check-operation]').trigger('click'); await flushPromises()
    expect(api.getPayoutOperation).toHaveBeenCalledWith(api.requestPayout.mock.calls[0][1])
    expect(api.requestPayout).toHaveBeenCalledTimes(1)
    api.requestPayout.mockResolvedValue({ id: 5 })
    await w.get('[data-test=retry-operation]').trigger('click'); await flushPromises()
    expect(api.requestPayout).toHaveBeenCalledTimes(2)
    expect(api.requestPayout.mock.calls[1]).toEqual(api.requestPayout.mock.calls[0])
  })
  it('recovers an uncertain cancellation with the same key after checking status', async () => {
    const payout = { id: 7, masked_label: 'bank', amount: '10.00', currency: 'USD', status: 'requested', created_at: '2026-01-01' }
    api.listPayouts.mockResolvedValue([payout]); api.getPayout.mockResolvedValue(payout)
    api.cancelPayout.mockRejectedValueOnce({ status: 0 }).mockResolvedValueOnce({ ...payout, status: 'cancelled' })
    const w = mountView(); await flushPromises()
    await w.findAll('button').find(b => b.text() === 'marketplace.cancelPayout')!.trigger('click')
    const confirm = Array.from(document.body.querySelectorAll('button')).find(b => b.textContent?.trim() === 'common.confirm')
    expect(confirm).toBeDefined(); confirm!.click(); await flushPromises()
    await w.get('[data-test=check-cancellation]').trigger('click'); await flushPromises()
    await w.get('[data-test=retry-cancellation]').trigger('click'); await flushPromises()
    expect(api.cancelPayout).toHaveBeenCalledTimes(2)
    expect(api.cancelPayout.mock.calls[1]).toEqual(api.cancelPayout.mock.calls[0])
    w.unmount()
  })

  it('retains an in-flight payout request across page navigation', async () => {
    api.requestPayout.mockReturnValue(new Promise(() => {}))
    const first = mountView(); await flushPromises()
    await first.get('[data-test=destination]').setValue('1'); await first.get('[data-test=amount]').setValue('10.00')
    await first.get('[data-test=request]').trigger('click'); first.unmount()
    const second = mountView(); await flushPromises()
    expect(second.text()).toContain('marketplace.operationUnknown')
    expect(second.get('[data-test=request]').attributes('disabled')).toBeDefined()
    second.unmount()
  })

})
